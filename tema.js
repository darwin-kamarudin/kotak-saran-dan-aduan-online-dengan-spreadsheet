(function terapkanTema() {
  const TINGKAT = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
  const valid = p => !!p && TINGKAT.every(n => /^#[0-9a-f]{6}$/i.test(String(p[n] || "")));

  const cfg = (typeof CONFIG_TEMA !== "undefined" && CONFIG_TEMA) ? CONFIG_TEMA : {};
  let palet = valid(cfg.paletKustom) ? cfg.paletKustom : PALET_TEMA[cfg.warna];
  if (!valid(palet)) {
    if (cfg.warna || cfg.paletKustom) console.warn("Tema tidak dikenali, memakai tema bawaan (blue). Pilihan: " + Object.keys(PALET_TEMA).join(", "));
    palet = PALET_TEMA.blue;
  }

  const rgb = hex => [1, 3, 5].map(i => parseInt(hex.substr(i, 2), 16)).join(" ");
  const root = document.documentElement;
  const warnaTailwind = {};
  TINGKAT.forEach(n => {
    root.style.setProperty("--tema-" + n, rgb(palet[n]));
    warnaTailwind[n] = "rgb(var(--tema-" + n + ") / <alpha-value>)";
  });

  // Daftarkan warna "tema" ke Tailwind CDN
  tailwind.config = { theme: { extend: { colors: { tema: warnaTailwind } } } };

  // Warna bilah browser di HP mengikuti tema
  let meta = document.querySelector('meta[name="theme-color"]');
  if (!meta) { meta = document.createElement("meta"); meta.name = "theme-color"; document.head.appendChild(meta); }
  meta.content = palet[900];
})();